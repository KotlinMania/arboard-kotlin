    @Test
    fun conversionBetweenWinAndRgba() {
        val initialData =
            byteArrayOf(
                100,
                100,
                255.toByte(),
                100,
                0,
                0,
                0,
                255.toByte(),
                255.toByte(),
                100,
                100,
                255.toByte(),
                100,
                255.toByte(),
                100,
                100,
            )

        var data = initialData.copyOf()
        WindowsClipboard.winToRgbaInPlace(data)

        data = initialData.copyOf()
        WindowsClipboard.rgbaToWinInPlace(data)

        data = initialData.copyOf()
        WindowsClipboard.winToRgbaInPlace(data)
        WindowsClipboard.rgbaToWinInPlace(data)
        assertContentEquals(initialData, data)

        data = initialData.copyOf()
        WindowsClipboard.rgbaToWinInPlace(data)
        WindowsClipboard.winToRgbaInPlace(data)
        assertContentEquals(initialData, data)
    }

